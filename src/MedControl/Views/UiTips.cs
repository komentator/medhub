    public static void Apply(DependencyObject root)
    {
        try
        {
            foreach (var b in Find<Button>(root))
            {
                if (b.ToolTip != null) continue;
                if (b.Content is string s && Map.TryGetValue(s.Trim(), out var tip))
                    b.ToolTip = tip;
            }
        }
        catch { }
    }

    private static List<T> Find<T>(DependencyObject root) where T : DependencyObject
    {
        var res = new List<T>();
        try
        {
            int n = VisualTreeHelper.GetChildrenCount(root);
            for (int i = 0; i < n; i++)
            {
                var ch = VisualTreeHelper.GetChild(root, i);
                if (ch is T t) res.Add(t);
                res.AddRange(Find<T>(ch));
            }
        }
        catch { }
        return res;
    }
